// Lists the C# files to process under the root, skipping build output, hidden folders and generated code.
namespace CSharpMinifier;

// Finds .cs files and tells generated ones apart.
internal static class SourceFiles
{
    // Folder names never walked into: build output and dependencies.
    private static readonly HashSet<string> SkippedDirs = ["bin", "obj", "node_modules", "packages"];

    // File name endings that mark generated code.
    private static readonly string[] GeneratedSuffixes = [".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs", ".AssemblyInfo.cs"];

    // The .cs files under each path (a file or a folder), sorted, without duplicates.
    public static List<string> Under(IEnumerable<string> paths)
    {
        var files = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var path in paths)
        {
            if (File.Exists(path))
                files.Add(Path.GetFullPath(path));
            else
                Walk(Path.GetFullPath(path), files);
        }
        return files.Where(f => f.EndsWith(".cs", StringComparison.OrdinalIgnoreCase)).ToList();
    }

    // Adds the .cs files in the folder and its subfolders, leaving out skipped and hidden folders.
    private static void Walk(string dir, SortedSet<string> files)
    {
        foreach (var file in Directory.EnumerateFiles(dir, "*.cs"))
            files.Add(file);
        foreach (var sub in Directory.EnumerateDirectories(dir))
        {
            var name = Path.GetFileName(sub);
            if (name.StartsWith('.') || SkippedDirs.Contains(name) || new DirectoryInfo(sub).LinkTarget != null)
                continue;
            Walk(sub, files);
        }
    }

    // True when the file name or an <auto-generated> marker at its top says a tool wrote it.
    public static bool IsGenerated(string path, string text)
    {
        if (GeneratedSuffixes.Any(s => path.EndsWith(s, StringComparison.OrdinalIgnoreCase)))
            return true;
        var head = text.Length > 2000 ? text[..2000] : text;
        return head.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase);
    }
}
