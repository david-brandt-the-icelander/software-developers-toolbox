// `zazzle flow generate`: generated code is the generators' job: each `generate` check whose inputs changed (or every one) runs, the files it rewrote are listed, and `--check` reports outputs that were stale and puts them back; agents never edit a generator's outputs by hand, reviews leave them out, and a branch update regenerates a conflicted output.
use super::policy::{Check, Policy};
use super::repo;
use super::verify;
use std::path::Path;
use std::time::Duration;

// The generators that apply to the change against `base` (every one without a base).
fn applicable<'a>(top: &Path, p: &'a Policy, base: Option<&str>) -> Result<Vec<&'a Check>, String> {
    let all = || p.checks.iter().filter(|c| c.kind == "generate").collect::<Vec<_>>();
    Ok(match base {
        Some(b) => {
            let changed = repo::changed(top, b, &repo::worktree_tree(top)?)?;
            all()
                .into_iter()
                .filter(|c| {
                    c.paths.is_empty()
                        || changed.iter().any(|x| repo::under(x, &c.paths) && !repo::under(x, &c.outputs))
                })
                .collect()
        }
        None => all(),
    })
}

// Runs one generator.
fn run(top: &Path, c: &Check, limit: Duration) -> Result<verify::Outcome, String> {
    let log = repo::state(top, "logs")?.join(format!("generate-{}.log", verify::safe(&c.name)));
    Ok(verify::run_check(top, c, &log, limit))
}

// Runs the generator that writes `path`, for a conflicted output in a branch update; None when no generator writes it.
pub fn regenerate(
    top: &Path,
    p: &Policy,
    path: &str,
    limit: Duration,
) -> Option<Result<verify::Outcome, String>> {
    let c = p.checks.iter().find(|c| c.kind == "generate" && repo::under(path, &c.outputs))?;
    Some(run(top, c, limit))
}

// Runs the generators that apply and returns the report and whether everything was current (`check`) or regenerated without error.
pub fn generate(
    top: &Path,
    p: &Policy,
    base: Option<&str>,
    check: bool,
    limit: Duration,
) -> Result<(String, bool), String> {
    let gens = applicable(top, p, base)?;
    if gens.is_empty() {
        let why = if p.checks.iter().any(|c| c.kind == "generate") {
            "no generator's inputs changed (run with --all to regenerate anyway)"
        } else {
            "no generator is configured (add kind \"generate\" checks with \"paths\" for inputs and \"outputs\" to .zazzle/flow.json)"
        };
        return Ok((format!("generate: {why}\n"), true));
    }
    let before = repo::worktree_tree(top)?;
    let mut out = String::from("generated by zazzle:\n");
    let mut ok = true;
    for c in &gens {
        let o = run(top, c, limit)?;
        ok &= o.status == "passed";
        out.push_str(&format!(
            "  {} {}: {}\n",
            if o.status == "passed" { "✓" } else { "✗" },
            c.name,
            o.summary()
        ));
    }
    let changed = repo::changed(top, &before, &repo::worktree_tree(top)?)?;
    let outputs: Vec<String> = gens.iter().flat_map(|c| c.outputs.clone()).collect();
    let stray: Vec<&String> = changed.iter().filter(|f| !repo::under(f, &outputs)).collect();
    if !stray.is_empty() {
        out.push_str(&format!(
            "  the generators also changed files outside their outputs: {}\n",
            stray.iter().map(|s| s.as_str()).collect::<Vec<_>>().join(", ")
        ));
    }
    match (check, changed.is_empty()) {
        (_, true) => out.push_str("-- the generated files are current\n"),
        (true, false) => {
            repo::restore(top, &before, &changed)?;
            out.push_str(&format!(
                "-- stale: regenerating changes {}; run `zazzle flow generate` and commit the result\n",
                changed.join(", ")
            ));
            ok = false;
        }
        (false, false) => {
            out.push_str(&format!("-- regenerated {}; commit them with the change\n", changed.join(", ")))
        }
    }
    Ok((out, ok))
}
