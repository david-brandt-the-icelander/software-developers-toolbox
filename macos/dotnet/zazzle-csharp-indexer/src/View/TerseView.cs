// Terse behavioural view of a C# file: hides usings, logging, regions, trivial constructors and log-and-rethrow catches, and shortens declarations and long local names, keeping source line numbers.
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.Text.RegularExpressions;

namespace ZazzleIndexer.View;

// One line of the view: a source line, possibly changed, or a note standing for the hidden lines Start to End.
public sealed record ViewLine(int Start, int End, string Text, bool Changed, bool Note);

// What the view does with XML doc comments: keep them, cut each to its first summary sentence, or hide them.
public enum DocMode { Full, Summary, None }

// Builds terse views; every rule is syntactic and conservative, so behaviour stays visible.
public static class TerseView
{
    private static readonly string[] LogMethods = ["Debug", "Info", "Information", "Warn", "Warning", "Error", "Fatal", "Trace", "Verbose", "Critical"];
    private static readonly string[] TelemetryMethods = ["SetTag", "AddTag", "AddEvent", "SetStatus", "SetBaggage", "AddBaggage", "RecordException", "AddException"];
    private const int MinShortened = 6;
    private static readonly SyntaxKind[] Access = [SyntaxKind.PublicKeyword, SyntaxKind.PrivateKeyword, SyntaxKind.ProtectedKeyword, SyntaxKind.InternalKeyword];

    // Strings at least this long (characters) become `"…"(N chars)`.
    public const int MinFoldedString = 240;
    // Collection initialisers with at least this many items spanning at least MinFoldedInitializerLines lines become `{ N items }`.
    public const int MinFoldedItems = 8;
    public const int MinFoldedInitializerLines = 6;
    // A doc summary is cut at this many characters.
    private const int MaxSummary = 200;

    // Parses a doc mode name (full, summary, none); null when unknown.
    public static DocMode? ParseDocMode(string? name) => name?.Trim().ToLowerInvariant() switch
    {
        "full" => DocMode.Full,
        "summary" => DocMode.Summary,
        "none" => DocMode.None,
        _ => null,
    };

    // Returns the view lines and, per step, how many places it changed; `docs` says what happens to XML doc comments (Full keeps everything, as before).
    public static (List<ViewLine> Lines, List<(string Step, int Count)> Steps) Build(string source, DocMode docs = DocMode.Full)
    {
        var tree = CSharpSyntaxTree.ParseText(source);
        var root = tree.GetCompilationUnitRoot();
        var plan = new Plan(tree.GetText());
        CollapseUsings(root, plan);
        CollapseConstructors(root, plan);
        CollapseRethrowCatches(root, plan);
        HideLogging(root, plan);
        HideRegions(root, plan);
        DropAccessModifiers(root, plan);
        UseVar(root, plan);
        ShortenLocals(tree, root, plan);
        if (IsGenerated(root))
            FoldGeneratedBodies(root, plan);
        FoldInitializers(root, plan);
        FoldStrings(root, plan);
        if (docs != DocMode.Full)
        {
            HideBanners(root, plan);
            FoldDocs(root, plan, docs);
        }
        return (plan.Render(), plan.Steps);
    }

    // True when the file starts with an auto-generated header.
    private static bool IsGenerated(CompilationUnitSyntax root) =>
        root.GetLeadingTrivia().Take(40).Any(t => t.ToString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase) || t.ToString().Contains("<autogenerated", StringComparison.OrdinalIgnoreCase));

    // Folds the bodies of methods, constructors and accessors of generated code to one line each.
    private static void FoldGeneratedBodies(CompilationUnitSyntax root, Plan plan)
    {
        foreach (var b in root.DescendantNodes().OfType<BlockSyntax>().Where(b => b.Parent is BaseMethodDeclarationSyntax or AccessorDeclarationSyntax or LocalFunctionStatementSyntax))
            plan.Fold(b.OpenBraceToken.SpanStart, b.CloseBraceToken.Span.End, $"{{ … {plan.LineCount(b)} lines }}", "generated bodies", 3);
    }

    // Folds long collection initialisers and collection expressions to `{ N items }`.
    private static void FoldInitializers(CompilationUnitSyntax root, Plan plan)
    {
        foreach (var n in root.DescendantNodes())
        {
            switch (n)
            {
                case InitializerExpressionSyntax { RawKind: (int)SyntaxKind.ArrayInitializerExpression or (int)SyntaxKind.CollectionInitializerExpression } i when i.Expressions.Count >= MinFoldedItems:
                    plan.Fold(i.OpenBraceToken.SpanStart, i.CloseBraceToken.Span.End, $"{{ {i.Expressions.Count} items }}", "initializers", MinFoldedInitializerLines);
                    break;
                case CollectionExpressionSyntax c when c.Elements.Count >= MinFoldedItems:
                    plan.Fold(c.OpenBracketToken.SpanStart, c.CloseBracketToken.Span.End, $"[ {c.Elements.Count} items ]", "initializers", MinFoldedInitializerLines);
                    break;
            }
        }
    }

    // Replaces very long string literals with their length.
    private static void FoldStrings(CompilationUnitSyntax root, Plan plan)
    {
        foreach (var n in root.DescendantNodes())
        {
            if (n is LiteralExpressionSyntax { RawKind: (int)SyntaxKind.StringLiteralExpression } or InterpolatedStringExpressionSyntax && n.Span.Length >= MinFoldedString)
                plan.Fold(n.SpanStart, n.Span.End, $"\"…\"({n.Span.Length} chars)", "long strings", 1);
        }
    }

    // Hides whole-line `// ------` banners.
    private static void HideBanners(CompilationUnitSyntax root, Plan plan)
    {
        foreach (var t in root.DescendantTrivia().Where(t => t.IsKind(SyntaxKind.SingleLineCommentTrivia)))
            if (Regex.IsMatch(t.ToString(), @"^//\s*([-=*#_~/])\1{3,}\s*$") && plan.OnlyOnLine(t.Span))
                plan.HideLine(plan.LineOf(t.SpanStart), "banners");
    }

    // Folds each multi-line XML doc comment to its one-line summary, or hides doc comments for DocMode.None.
    private static void FoldDocs(CompilationUnitSyntax root, Plan plan, DocMode mode)
    {
        foreach (var t in root.DescendantTrivia().Where(t => t.IsKind(SyntaxKind.SingleLineDocumentationCommentTrivia)))
        {
            if (!plan.OnlyOnLine(t.FullSpan, true))
                continue;
            var (start, end) = plan.LinesOf(t.FullSpan);
            if (mode == DocMode.None)
            {
                plan.HideRange(start, end, "docs hidden");
                continue;
            }
            if (t.GetStructure() is not DocumentationCommentTriviaSyntax doc)
                continue;
            var summary = Summarize(doc);
            if (summary is null)
                continue;
            var folded = plan.IndentOf(start) + "/// " + summary;
            if (end > start || folded.Length < plan.LineLength(start))
                plan.FoldLines(start, end, folded, "docs folded");
        }
    }

    // Returns the first sentence of a doc comment's summary, or null when it has none.
    public static string? Summarize(DocumentationCommentTriviaSyntax doc)
    {
        var summary = doc.Content.OfType<XmlElementSyntax>().FirstOrDefault(e => e.StartTag.Name.LocalName.Text == "summary");
        if (summary is null)
            return null;
        var raw = string.Concat(summary.Content.Select(c => c.ToFullString()));
        raw = Regex.Replace(raw, @"^\s*///", "", RegexOptions.Multiline);
        raw = Regex.Replace(raw, @"<(?:see|seealso)\s+cref=""([^""]+)""\s*/?>(?:</(?:see|seealso)>)?", m => m.Groups[1].Value.Replace("{", "<").Replace("}", ">"));
        raw = Regex.Replace(raw, @"<paramref\s+name=""([^""]+)""\s*/>", "$1");
        raw = Regex.Replace(raw, @"<[^>]+>", " ");
        raw = System.Net.WebUtility.HtmlDecode(Regex.Replace(raw, @"\s+", " ").Trim());
        if (raw.Length == 0)
            return null;
        var m = Regex.Match(raw, @"^(.+?[.!?])(\s|$)");
        var sentence = m.Success ? m.Groups[1].Value : raw;
        return sentence.Length > MaxSummary ? sentence[..(MaxSummary - 1)].TrimEnd() + "…" : sentence;
    }

    // Collapses each block of using directives into one line.
    private static void CollapseUsings(CompilationUnitSyntax root, Plan plan)
    {
        IEnumerable<SyntaxList<UsingDirectiveSyntax>> blocks = [root.Usings, .. root.DescendantNodes().OfType<BaseNamespaceDeclarationSyntax>().Select(n => n.Usings)];
        foreach (var usings in blocks.Where(u => u.Count > 0))
            plan.Hide(usings.First(), usings.Last(), $"{usings.Count} using(s)", "usings");
    }

    // True for a statement whose only effect is logging or tracing, with no side effects in its arguments.
    public static bool IsLogging(StatementSyntax s)
    {
        if (s is LocalDeclarationStatementSyntax { UsingKeyword.RawKind: not 0 } local)
            return local.Declaration.Variables.All(v => v.Initializer?.Value is InvocationExpressionSyntax inv && CalleeName(inv) == "StartActivity");
        if (s is not ExpressionStatementSyntax { Expression: var e } || HasSideEffects(e))
            return false;
        return e switch
        {
            InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax m } => IsLogCall(Last(m.Expression), m.Name.Identifier.Text),
            ConditionalAccessExpressionSyntax { Expression: var r, WhenNotNull: InvocationExpressionSyntax { Expression: MemberBindingExpressionSyntax b } } => IsLogCall(Last(r), b.Name.Identifier.Text),
            _ => false,
        };
    }

    // True for a call on a logger, Debug/Trace, or a tracing span.
    private static bool IsLogCall(string receiver, string method)
    {
        var r = receiver.TrimStart('_').ToLowerInvariant();
        if (receiver is "Debug" or "Trace")
            return true;
        if ((r is "log" or "logs" or "logging" || r.EndsWith("logger")) && (method.StartsWith("Log", StringComparison.Ordinal) || LogMethods.Contains(method)))
            return true;
        return (r.Contains("activity") || r.Contains("span")) && TelemetryMethods.Contains(method);
    }

    // Returns the last identifier of a receiver expression, such as `_logger` in `this._logger`.
    private static string Last(ExpressionSyntax e) => e switch
    {
        MemberAccessExpressionSyntax m => m.Name.Identifier.Text,
        IdentifierNameSyntax id => id.Identifier.Text,
        _ => e.ToString(),
    };

    // Returns the method name an invocation calls.
    private static string CalleeName(InvocationExpressionSyntax inv) => inv.Expression switch
    {
        MemberAccessExpressionSyntax m => m.Name.Identifier.Text,
        IdentifierNameSyntax id => id.Identifier.Text,
        _ => "",
    };

    // True when an expression assigns, increments, awaits or creates a lambda that might.
    private static bool HasSideEffects(ExpressionSyntax e) => e.DescendantNodes().Any(n =>
        n is AssignmentExpressionSyntax or AwaitExpressionSyntax
        || n is PrefixUnaryExpressionSyntax { RawKind: (int)SyntaxKind.PreIncrementExpression or (int)SyntaxKind.PreDecrementExpression }
        || n is PostfixUnaryExpressionSyntax { RawKind: (int)SyntaxKind.PostIncrementExpression or (int)SyntaxKind.PostDecrementExpression });

    // Hides logging statements, and `if (logger.IsEnabled(..))` blocks that only log.
    private static void HideLogging(CompilationUnitSyntax root, Plan plan)
    {
        foreach (var s in root.DescendantNodes().OfType<StatementSyntax>())
        {
            if (IsLogging(s) && s.Parent is BlockSyntax or SwitchSectionSyntax)
                plan.Hide(s, s, null, "log statements");
            else if (s is IfStatementSyntax { Else: null } i && i.Condition.ToString().Contains("IsEnabled") && Body(i.Statement).All(IsLogging))
                plan.Hide(s, s, null, "log statements");
        }
    }

    // Returns the statements of a block, or the statement itself.
    private static IEnumerable<StatementSyntax> Body(StatementSyntax s) => s is BlockSyntax b ? b.Statements : [s];

    // True for a statement that only stores a value: `x = y;`, `this.x = y;` or `x = y ?? throw ..;`.
    private static bool IsStore(StatementSyntax s) =>
        s is ExpressionStatementSyntax { Expression: AssignmentExpressionSyntax { RawKind: (int)SyntaxKind.SimpleAssignmentExpression, Right: var r } }
        && (r is IdentifierNameSyntax || r is BinaryExpressionSyntax { RawKind: (int)SyntaxKind.CoalesceExpression, Right: ThrowExpressionSyntax });

    // Collapses constructors that only store their parameters into one line naming the parameters.
    private static void CollapseConstructors(CompilationUnitSyntax root, Plan plan)
    {
        foreach (var c in root.DescendantNodes().OfType<ConstructorDeclarationSyntax>())
        {
            var stores = c.Body is { } b ? b.Statements.All(IsStore) : c.ExpressionBody?.Expression is AssignmentExpressionSyntax;
            if (!stores || c.Modifiers.Any(SyntaxKind.StaticKeyword))
                continue;
            var init = c.Initializer is { } i ? $" : {i.ThisOrBaseKeyword.Text}({i.ArgumentList.Arguments.Count} args)" : "";
            var what = c.Body is { Statements.Count: 0 } ? "empty" : "only assigns fields";
            plan.Hide(c, c, $"ctor({string.Join(", ", c.ParameterList.Parameters.Select(p => $"{p.Type} {p.Identifier.Text}"))}){init}: {what}", "constructors");
        }
    }

    // Collapses catch clauses that only log and rethrow.
    private static void CollapseRethrowCatches(CompilationUnitSyntax root, Plan plan)
    {
        foreach (var c in root.DescendantNodes().OfType<CatchClauseSyntax>())
        {
            var body = c.Block.Statements;
            var rethrows = body.Count > 0 && body.Last() is ThrowStatementSyntax { Expression: null } && body.SkipLast(1).All(IsLogging);
            if (rethrows && c.Filter is null)
                plan.Hide(c, c, $"catch ({c.Declaration?.Type.ToString() ?? "all"}): logs and rethrows", "log-and-rethrow catches");
        }
    }

    // Hides #region and #endregion lines.
    private static void HideRegions(CompilationUnitSyntax root, Plan plan)
    {
        foreach (var t in root.DescendantTrivia(descendIntoTrivia: true))
            if (t.IsKind(SyntaxKind.RegionDirectiveTrivia) || t.IsKind(SyntaxKind.EndRegionDirectiveTrivia))
                plan.HideLine(t.GetLocation().GetLineSpan().StartLinePosition.Line, "regions");
    }

    // Removes public, private, protected and internal from declarations.
    private static void DropAccessModifiers(CompilationUnitSyntax root, Plan plan)
    {
        foreach (var t in root.DescendantTokens().Where(t => Access.Any(k => t.IsKind(k)) && t.Parent is MemberDeclarationSyntax or AccessorDeclarationSyntax))
            plan.Change(TextSpan.FromBounds(t.Span.Start, t.TrailingTrivia.Span.End), "", "access modifiers");
    }

    // Uses var where a local's type is spelled out on the right: `new T(..)`, `(T)x` or `x as T`.
    private static void UseVar(CompilationUnitSyntax root, Plan plan)
    {
        foreach (var d in root.DescendantNodes().OfType<LocalDeclarationStatementSyntax>())
        {
            var decl = d.Declaration;
            if (d.IsConst || decl.Type.IsVar || decl.Variables.Count != 1 || decl.Variables[0].Initializer?.Value is not { } value)
                continue;
            var spelled = value switch
            {
                ObjectCreationExpressionSyntax o => o.Type,
                CastExpressionSyntax c => c.Type,
                BinaryExpressionSyntax { RawKind: (int)SyntaxKind.AsExpression, Right: TypeSyntax t } => t,
                _ => null,
            };
            if (spelled is not null && spelled.ToString() == decl.Type.ToString())
                plan.Change(decl.Type.Span, "var", "var");
        }
    }

    // Returns a short name for a long local: the initials of its camelCase words, or the first three letters of a single word; null when not worth it.
    public static string? Abbreviate(string name)
    {
        if (name.Length < MinShortened)
            return null;
        var words = Regex.Matches(name, "[A-Z]?[a-z0-9]+|[A-Z]+(?![a-z])").Select(m => m.Value).ToList();
        var shortName = words.Count > 1 ? string.Concat(words.Select(w => char.ToLowerInvariant(w[0]))) : name[..3].ToLowerInvariant();
        return shortName.Length < name.Length && char.IsLetter(shortName[0]) ? shortName : null;
    }

    // True when a name cannot stand for a local: a keyword or contextual keyword such as `var`.
    private static bool Reserved(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(name) != SyntaxKind.None;

    // Shortens long local variable names, binding with a compilation of this file alone so only the local's own uses change; parameters keep their names.
    private static void ShortenLocals(SyntaxTree tree, CompilationUnitSyntax root, Plan plan)
    {
        var model = CSharpCompilation.Create("view", [tree]).GetSemanticModel(tree);
        var declarators = root.DescendantNodes().Where(n => n is VariableDeclaratorSyntax { Parent.Parent: LocalDeclarationStatementSyntax } or ForEachStatementSyntax or CatchDeclarationSyntax or SingleVariableDesignationSyntax);
        var taken = new Dictionary<SyntaxNode, HashSet<string>>();
        foreach (var node in declarators)
        {
            if (model.GetDeclaredSymbol(node) is not ILocalSymbol local || Abbreviate(local.Name) is not { } wanted)
                continue;
            var scope = (SyntaxNode?)node.FirstAncestorOrSelf<MemberDeclarationSyntax>() ?? root;
            var uses = scope.DescendantNodes().OfType<IdentifierNameSyntax>()
                .Where(id => id.Identifier.ValueText == local.Name && SymbolEqualityComparer.Default.Equals(model.GetSymbolInfo(id).Symbol, local)).ToList();
            if (uses.Any(u => u.Ancestors().OfType<InvocationExpressionSyntax>().Any(i => i.Expression is IdentifierNameSyntax { Identifier.ValueText: "nameof" })))
                continue;
            if (!taken.TryGetValue(scope, out var names))
                taken[scope] = names = scope.DescendantTokens().Where(t => t.IsKind(SyntaxKind.IdentifierToken)).Select(t => t.ValueText).ToHashSet();
            var shortName = wanted;
            for (var n = 2; names.Contains(shortName) || Reserved(shortName); n++)
                shortName = wanted + n;
            names.Add(shortName);
            var declared = node switch
            {
                VariableDeclaratorSyntax v => v.Identifier,
                ForEachStatementSyntax f => f.Identifier,
                CatchDeclarationSyntax c => c.Identifier,
                _ => ((SingleVariableDesignationSyntax)node).Identifier,
            };
            plan.Change(declared.Span, shortName, "locals shortened");
            foreach (var u in uses)
                plan.Change(u.Identifier.Span, shortName, null);
        }
    }

    // Collects hidden ranges and single-line text changes, then renders the view.
    private sealed class Plan(SourceText text)
    {
        private readonly List<(int Start, int End, string? Note)> _hidden = [];
        private readonly List<TextChange> _changes = [];
        private readonly List<(int Start, int End, string Text)> _folds = [];
        public List<(string Step, int Count)> Steps { get; } = [];

        // Returns the zero-based line holding a position.
        public int LineOf(int position) => text.Lines.GetLineFromPosition(position).LineNumber;

        // Returns the first and last zero-based line a span covers, not counting a trailing line break.
        public (int Start, int End) LinesOf(TextSpan span) => (LineOf(span.Start), LineOf(Math.Max(span.Start, span.End - 1)));

        // Returns how many source lines a node covers.
        public int LineCount(SyntaxNode n)
        {
            var (a, b) = LinesOf(n.Span);
            return b - a + 1;
        }

        // Returns the leading whitespace of a line.
        public string IndentOf(int line)
        {
            var s = text.Lines[line].ToString();
            return s[..(s.Length - s.TrimStart().Length)];
        }

        // Returns the length of a line without its line break.
        public int LineLength(int line) => text.Lines[line].Span.Length;

        // True when nothing but whitespace shares the first line before the span, and, unless `wholeLines`, nothing follows it on the last line.
        public bool OnlyOnLine(TextSpan span, bool wholeLines = false)
        {
            var first = text.Lines.GetLineFromPosition(span.Start);
            var last = text.Lines.GetLineFromPosition(Math.Max(span.Start, span.End - 1));
            return text.ToString(TextSpan.FromBounds(first.Start, span.Start)).Trim().Length == 0
                && (wholeLines || text.ToString(TextSpan.FromBounds(Math.Min(span.End, last.End), last.End)).Trim().Length == 0);
        }

        // True when the lines start to end overlap lines already hidden or folded.
        private bool Taken(int start, int end) => _hidden.Any(h => h.Start <= end && start <= h.End) || _folds.Any(f => f.Start <= end && start <= f.End);

        // Hides whole lines with no note; skipped when they overlap lines already hidden or folded.
        public void HideRange(int start, int end, string step)
        {
            if (Taken(start, end))
                return;
            _hidden.Add((start, end, null));
            Count(step);
        }

        // Replaces a character range with `replacement`: as one view line standing for all the lines it covers when there are at least `minLines`; skipped when those lines are already hidden or folded.
        public void Fold(int from, int to, string replacement, string step, int minLines)
        {
            var (start, end) = LinesOf(TextSpan.FromBounds(from, to));
            if (end - start + 1 < minLines || Taken(start, end))
                return;
            var prefix = text.ToString(TextSpan.FromBounds(text.Lines[start].Start, from));
            var suffix = text.ToString(TextSpan.FromBounds(to, Math.Max(to, text.Lines[end].End)));
            _folds.Add((start, end, (prefix + replacement + suffix).TrimEnd()));
            Count(step);
        }

        // Folds the whole lines start to end into one line of text.
        public void FoldLines(int start, int end, string whole, string step)
        {
            if (Taken(start, end))
                return;
            _folds.Add((start, end, whole));
            Count(step);
        }

        // Counts one change under a step name.
        private void Count(string step)
        {
            var i = Steps.FindIndex(s => s.Step == step);
            if (i < 0)
                Steps.Add((step, 1));
            else
                Steps[i] = (step, Steps[i].Count + 1);
        }

        // Hides the lines from one node to another, with a note line or none, if they hold nothing else and are not hidden yet; collapses run before line-level hiding so they win.
        public void Hide(SyntaxNode first, SyntaxNode last, string? note, string step)
        {
            var start = text.Lines.GetLineFromPosition(first.SpanStart).LineNumber;
            var end = text.Lines.GetLineFromPosition(last.Span.End).LineNumber;
            var leading = first.GetLeadingTrivia().Where(t => t.IsKind(SyntaxKind.SingleLineDocumentationCommentTrivia)).Select(t => text.Lines.GetLineFromPosition(t.SpanStart).LineNumber);
            if (note is not null && leading.Any())
                start = Math.Min(start, leading.Min());
            var firstLine = text.Lines.GetLineFromPosition(first.SpanStart);
            var before = text.ToString(TextSpan.FromBounds(firstLine.Start, first.SpanStart)).Trim();
            var after = text.ToString(TextSpan.FromBounds(last.Span.End, text.Lines[end].End)).Trim();
            if (before.Length > 0 || after.Length > 0 && !after.StartsWith("//"))
                return;
            if (_hidden.Any(h => h.Start <= end && start <= h.End))
                return;
            _hidden.Add((start, end, note));
            Count(step);
        }

        // Hides one line with no note.
        public void HideLine(int line, string step)
        {
            if (_hidden.Any(h => h.Start <= line && line <= h.End))
                return;
            _hidden.Add((line, line, null));
            Count(step);
        }

        // Records a change that stays within one line.
        public void Change(TextSpan span, string replacement, string? step)
        {
            if (text.Lines.GetLineFromPosition(span.Start).LineNumber != text.Lines.GetLineFromPosition(span.End).LineNumber)
                return;
            _changes.Add(new TextChange(span, replacement));
            if (step is not null)
                Count(step);
        }

        // Produces the view: hidden ranges become notes or gaps, changed lines are marked, and blank runs shrink to one.
        public List<ViewLine> Render()
        {
            var lines = new List<ViewLine>();
            for (var i = 0; i < text.Lines.Count; i++)
            {
                var hi = _hidden.FindIndex(h => h.Start <= i && i <= h.End);
                if (hi >= 0)
                {
                    var (start, end, note) = _hidden[hi];
                    if (note is not null)
                        lines.Add(new ViewLine(start + 1, end + 1, "⋯ " + note, false, true));
                    i = end;
                    continue;
                }
                var fi = _folds.FindIndex(f => f.Start <= i && i <= f.End);
                if (fi >= 0)
                {
                    var (fs, fe, ft) = _folds[fi];
                    lines.Add(fs == fe ? new ViewLine(fs + 1, fs + 1, ft, true, false) : new ViewLine(fs + 1, fe + 1, ft, false, true));
                    i = fe;
                    continue;
                }
                var line = text.Lines[i];
                var mine =_changes.Where(c => line.Span.Contains(c.Span.Start)).OrderByDescending(c => c.Span.Start).ToList();
                var s = line.ToString();
                foreach (var c in mine)
                    s = s.Remove(c.Span.Start - line.Start, c.Span.Length).Insert(c.Span.Start - line.Start, c.NewText!);
                s = s.TrimEnd();
                if (s.Length == 0 && lines.Count > 0 && lines[^1].Text.Length == 0)
                    continue;
                lines.Add(new ViewLine(i + 1, i + 1, s, mine.Count > 0, false));
            }
            return lines;
        }
    }

    // Formats view lines for clients: `N\ttext`, `N~\ttext` for a changed line, `A-B\t⋯ note` for hidden lines.
    public static string Format(IEnumerable<ViewLine> lines) => string.Join('\n', lines.Select(l =>
        l.Note ? $"{l.Start}-{l.End}\t{l.Text}" : l.Changed ? $"{l.Start}~\t{l.Text}" : $"{l.Start}\t{l.Text}"));
}
